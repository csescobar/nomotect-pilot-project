require "json"

module ServiceDeskBenchmark
  ITERATIONS = 20

  class << self
    def call(iterations: ITERATIONS)
      raise "service-desk benchmark is only available in development" unless Rails.env.development?

      organization = Organization.find_by(slug: "acme-services")
      raise "run demo:seed before benchmarking" unless organization

      measurements = {
        "visible_to" => measure { ServiceRequests::VisibleTo.new(user: sample_user(organization), organization: organization).call.count },
        "grid_definition" => measure { GridEngine::Catalog.fetch("service_requests") },
        "grid_scope" => measure { GridEngine::Catalog.scope_for("service_requests", user: sample_user(organization), organization: organization).count },
        "create" => measure { create_request(organization) },
        "sla_target" => measure { ServiceRequests::SlaTarget.call(priority: :critical) }
      }

      write_report!(measurements, iterations: iterations)
    end

    private

    def measure(&block)
      timings = ITERATIONS.times.map do
        started = Process.clock_gettime(Process::CLOCK_MONOTONIC)
        block.call
        (Process.clock_gettime(Process::CLOCK_MONOTONIC) - started) * 1000.0
      end
      {
        "samples" => timings.size,
        "min_ms" => timings.min.round(3),
        "max_ms" => timings.max.round(3),
        "avg_ms" => (timings.sum / timings.size).round(3)
      }
    end

    def sample_user(organization)
      organization.memberships.find_by!(role: "support_agent").user
    end

    def create_request(organization)
      requester = organization.memberships.find_by!(role: "requester").user
      ServiceRequest.transaction(requires_new: true) do
        ServiceRequests::Create.new(actor: requester).call(
          organization: organization,
          attributes: {
            title: "Benchmark request",
            description: "Generated by service-desk-benchmark for performance evidence.",
            category: "other",
            priority: "low",
            status: "open"
          }
        ).record
        raise ActiveRecord::Rollback
      end
    end

    def write_report!(measurements, iterations:)
      report = {
        "schema_version" => 1,
        "tool" => "service-desk-benchmark",
        "environment" => { "rails_env" => Rails.env, "ruby" => RUBY_VERSION },
        "iterations" => iterations,
        "measurements" => measurements,
        "generated_at" => Time.current.utc.iso8601
      }
      path = Rails.root.join("tmp/validation/service-desk-performance.json")
      path.dirname.mkpath
      path.write(JSON.pretty_generate(report))
      report
    end
  end
end
